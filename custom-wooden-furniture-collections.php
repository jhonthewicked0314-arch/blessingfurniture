<script>
(function(){
    // Tab switching
    var tabs = document.querySelectorAll('.coll-tab');
    var panels = document.querySelectorAll('.coll-panel');
    tabs.forEach(function(tab){
        tab.addEventListener('click', function(){
            tabs.forEach(function(t){ t.classList.remove('active'); });
            tab.classList.add('active');
            var target = tab.getAttribute('data-tab');
            panels.forEach(function(p){
                p.classList.remove('active');
                if(p.getAttribute('data-panel') === target) p.classList.add('active');
            });
        });
    });

    // Modal
    var overlay = document.getElementById('collModalOverlay');
    var modalName = document.getElementById('modalProductName');
    var formProductName = document.getElementById('formProductName');
    var closeBtn = document.getElementById('collModalClose');
    var form = document.getElementById('collForm');

    function openModal(name){
        modalName.textContent = name;
        formProductName.value = name;
        overlay.classList.add('open');
        document.body.classList.add('coll-modal-open');
    }
    function closeModal(){
        overlay.classList.remove('open');
        document.body.classList.remove('coll-modal-open');
        resetForm();
    }
    function resetForm(){
        form.reset();
        form.querySelectorAll('.coll-pill.selected').forEach(function(p){ p.classList.remove('selected'); });
        form.querySelectorAll('.coll-swatch.selected').forEach(function(s){ s.classList.remove('selected'); });
        document.getElementById('customColorWrap').classList.remove('visible');
        document.getElementById('fieldWoodType').value = '';
        document.getElementById('fieldFinishType').value = '';
        document.getElementById('fieldColorShade').value = '';
    }

    // Card click -> open modal
    document.querySelectorAll('.coll-card-btn').forEach(function(btn){
        btn.addEventListener('click', function(e){
            e.stopPropagation();
            var card = btn.closest('.coll-card');
            openModal(card.getAttribute('data-product'));
        });
    });
    document.querySelectorAll('.coll-card').forEach(function(card){
        card.addEventListener('click', function(){
            openModal(card.getAttribute('data-product'));
        });
    });

    closeBtn.addEventListener('click', closeModal);
    overlay.addEventListener('click', function(e){ if(e.target === overlay) closeModal(); });
    document.addEventListener('keydown', function(e){ if(e.key === 'Escape') closeModal(); });

    // Pill selection
    document.querySelectorAll('.coll-pill-group').forEach(function(group){
        var field = group.getAttribute('data-field');
        group.querySelectorAll('.coll-pill').forEach(function(pill){
            pill.addEventListener('click', function(){
                group.querySelectorAll('.coll-pill').forEach(function(p){ p.classList.remove('selected'); });
                pill.classList.add('selected');
                var hiddenId = field === 'wood_type' ? 'fieldWoodType' : 'fieldFinishType';
                document.getElementById(hiddenId).value = pill.getAttribute('data-value');
            });
        });
    });

    // Swatch selection
    document.querySelectorAll('.coll-swatch').forEach(function(sw){
        sw.addEventListener('click', function(){
            document.querySelectorAll('.coll-swatch').forEach(function(s){ s.classList.remove('selected'); });
            sw.classList.add('selected');
            var color = sw.getAttribute('data-color');
            document.getElementById('fieldColorShade').value = color;
            var wrap = document.getElementById('customColorWrap');
            if(color === 'Custom'){ wrap.classList.add('visible'); } else { wrap.classList.remove('visible'); document.getElementById('customColorInput').value = ''; }
        });
    });

    // Toast
    function showToast(msg, type){
        var toast = document.getElementById('collToast');
        toast.textContent = msg;
        toast.className = 'coll-toast ' + type + ' show';
        setTimeout(function(){ toast.classList.remove('show'); }, 4000);
    }

    // Gather form data
    function getFormData(){
        return {
            product: formProductName.value,
            wood: document.getElementById('fieldWoodType').value,
            finish: document.getElementById('fieldFinishType').value,
            color: document.getElementById('fieldColorShade').value,
            customColor: document.getElementById('customColorInput').value,
            size: form.querySelector('[name="size"]').value,
            requirements: form.querySelector('[name="requirements"]').value
        };
    }

    // WhatsApp
    document.getElementById('btnWhatsApp').addEventListener('click', function(){
        var d = getFormData();
        if(!d.wood || !d.finish){ showToast('Please select Wood Type and Finish Type.', 'error'); return; }
        var msg = 'Hi, I would like to customize:\n';
        msg += '🪵 Product: ' + d.product + '\n';
        msg += '🌳 Wood: ' + d.wood + '\n';
        msg += '✨ Finish: ' + d.finish + '\n';
        if(d.color) msg += '🎨 Shade: ' + (d.color === 'Custom' ? d.customColor || 'Custom' : d.color) + '\n';
        if(d.size) msg += '📐 Size: ' + d.size + '\n';
        if(d.requirements) msg += '📝 Notes: ' + d.requirements + '\n';
        window.open('https://wa.me/919894779314?text=' + encodeURIComponent(msg), '_blank');
    });

    // Email via PHP mail
    document.getElementById('btnEmail').addEventListener('click', function(){
        var d = getFormData();
        if(!d.wood || !d.finish){ showToast('Please select Wood Type and Finish Type.', 'error'); return; }
        
        var uName = form.querySelector('[name="user_name"]').value.trim();
        var uEmail = form.querySelector('[name="user_email"]').value.trim();
        var uPhone = form.querySelector('[name="user_phone"]').value.trim();
        if(!uName || !uEmail || !uPhone){
            showToast('Please provide your Name, Email, and Phone Number.', 'error');
            return;
        }

        var fd = new FormData(form);
        var btn = document.getElementById('btnEmail');
        btn.textContent = 'Sending...';
        btn.disabled = true;
        fetch('collections-mail.php', { method: 'POST', body: fd })
        .then(function(r){ return r.json(); })
        .then(function(data){
            if(data.status === 'success'){
                showToast(data.message, 'success');
                closeModal();
            } else {
                showToast(data.message, 'error');
            }
        })
        .catch(function(){
            showToast('Something went wrong. Please try WhatsApp instead.', 'error');
        })
        .finally(function(){
            btn.innerHTML = '<svg viewBox="0 0 24 24" width="18" height="18" stroke="#B5651D" fill="none" stroke-width="2"><rect x="2" y="4" width="20" height="16" rx="2"/><path d="m22 7-8.97 5.7a1.94 1.94 0 0 1-2.06 0L2 7"/></svg> Send via Email';
            btn.disabled = false;
        });
    });
})();
</script>
